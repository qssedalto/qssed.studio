import assert from 'node:assert/strict';
import vm from 'node:vm';
import { MemoryR2 } from './helpers/memory-r2.mjs';
import { handleTexProjectFiles } from '../studio/tex-project-files-api.js';
import { texFileContentDigest,TEX_FILE_DIGEST_RUNTIME } from '../studio/tex-file-revision.js';
import { WORK_TEX_EXPLORER_TREE } from '../studio/ui-work-tex-explorer-tree.js';
import { TEX_FILE_MODAL_RUNTIME } from '../studio/ui-tex-file-modal-runtime.js';
const owner='11111111-1111-4111-8111-111111111111',id='22222222-2222-4222-8222-222222222222';
const key=`_system/tex-documents/${owner}/${id}.json`,store=new MemoryR2();
const original={name:'intro.tex',encoding:'utf8',content:'Original'};
store.seed(key,{id,owner_id:owner,source:'Main',engine:'xelatex',files:[original],project_type:'blank',title:'Test'});
const send=async(file)=>handleTexProjectFiles(new Request('https://work.qsseda.com/api/tex/files',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({document_id:id,operation:'replace',files:[file]})}),{STORAGE:store},owner);
const oldHash=await texFileContentDigest(original);
assert.equal((await send({...original,content:'Missing revision'})).status,428);
assert.equal((await send({...original,content:'First save',expected_sha256:oldHash})).status,200);
assert.equal((await send({...original,content:'Stale overwrite',expected_sha256:oldHash})).status,409);
assert.equal(store.document(key).files[0].content,'First save');
const current={...original,content:'First save'},currentHash=await texFileContentDigest(current);
store.seed(key,{...store.document(key),source:'Unrelated main edit'});
assert.equal((await send({...original,content:'Second save',expected_sha256:currentHash})).status,200,'Unrelated source edits must not cause a false file conflict');
assert.equal(store.document(key).source,'Unrelated main edit');
const digest=vm.runInNewContext('('+TEX_FILE_DIGEST_RUNTIME+')',{TextEncoder,crypto});
for(const content of ['','hello','\u4e2d\u6587\n\u{1f600}','a\0b'])assert.equal(await digest({...original,content}),await texFileContentDigest({...original,content}));
new vm.Script(WORK_TEX_EXPLORER_TREE);new vm.Script(TEX_FILE_MODAL_RUNTIME);
assert(WORK_TEX_EXPLORER_TREE.includes('expected_sha256:await texFileContentDigest(original)'));
assert(WORK_TEX_EXPLORER_TREE.includes("if(hasPendingAssetChange()||assetSaveInFlight)") &&
  WORK_TEX_EXPLORER_TREE.includes("activeTextValue()!==String(selected.content??'')"),
  "Unsaved navigation guard must compare actual source to the saved file, not a stale edited flag");
assert(TEX_FILE_MODAL_RUNTIME.includes('if(editText.value===submitted)editDialog.close()'));
assert(TEX_FILE_MODAL_RUNTIME.includes("editDialog.addEventListener('cancel', event => { event.preventDefault(); closeText();"));
